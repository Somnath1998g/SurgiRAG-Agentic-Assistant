def validate_config():
    """
    Basic startup validation.
    Call this once when starting the application.
    """

    errors = []

    if not GROQ_API_KEY:
        errors.append(
            "GROQ_API_KEY is missing from .env"
        )

    if not FAISS_INDEX_PATH.exists():
        errors.append(
            f"FAISS index not found: {FAISS_INDEX_PATH}"
        )

    if not VECTOR_METADATA_PATH.exists():
        errors.append(
            f"Vector metadata not found: {VECTOR_METADATA_PATH}"
        )

    if not RAG_CHUNKS_METADATA_PATH.exists():
        errors.append(
            f"RAG chunks metadata not found: "
            f"{RAG_CHUNKS_METADATA_PATH}"
        )

    if errors:
        raise RuntimeError(
            "\n".join(errors)
        )

    return True


